#!/usr/bin/env bash
# Render the Homebrew formula for one release from the .sha256 files attached to it.
#
# Usage: homebrew-formula.sh <tag> <owner/repo> <server-url> <dir-with-sha256-files>
# The release workflow runs this and pushes the output to gordlea/homebrew-tap as
# Formula/deep-voice-privilege.rb. Each sha file is `sha256sum` output: "<hash>  <file>".
# Only the macOS and Linux archives feed the formula; the Windows zip is a release asset only.
set -euo pipefail

if [ $# -ne 4 ]; then
  echo "usage: $0 <tag> <owner/repo> <server-url> <sha-dir>" >&2
  exit 2
fi
tag=$1 repo=$2 server=$3 dir=$4
version=${tag#v}
base="${server}/${repo}/releases/download/${tag}"

sha_for() {
  local target=$1 file hash
  file="${dir}/deep-voice-privilege-${tag}-${target}.tar.gz.sha256"
  [ -f "$file" ] || { echo "missing ${file}" >&2; exit 1; }
  hash=$(awk 'NR == 1 { print $1 }' "$file")
  [[ "$hash" =~ ^[0-9a-f]{64}$ ]] || { echo "no sha256 in ${file}" >&2; exit 1; }
  printf '%s' "$hash"
}

# Validate every checksum before printing anything, so a missing asset fails the job instead
# of producing a half-rendered formula (an exit inside $(...) would only end that subshell).
sha_mac_arm=$(sha_for aarch64-apple-darwin)
sha_mac_intel=$(sha_for x86_64-apple-darwin)
sha_linux_arm=$(sha_for aarch64-unknown-linux-gnu)
sha_linux_intel=$(sha_for x86_64-unknown-linux-gnu)

block() {
  local arch=$1 target=$2 hash=$3
  cat <<RUBY
    on_${arch} do
      url "${base}/deep-voice-privilege-${tag}-${target}.tar.gz"
      sha256 "${hash}"
    end
RUBY
}

cat <<RUBY
# Generated by ${repo}'s release workflow for ${tag}. Do not edit by hand.
class DeepVoicePrivilege < Formula
  desc "Pitch-shift your mic into a virtual device so meeting apps hear a deeper voice"
  homepage "${server}/${repo}"
  version "${version}"
  license "MIT-0"

  on_macos do
$(block arm aarch64-apple-darwin "$sha_mac_arm")
$(block intel x86_64-apple-darwin "$sha_mac_intel")
  end

  on_linux do
$(block arm aarch64-unknown-linux-gnu "$sha_linux_arm")
$(block intel x86_64-unknown-linux-gnu "$sha_linux_intel")
  end

  def install
    bin.install "deep-voice-privilege"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/deep-voice-privilege --version")
  end
end
RUBY
